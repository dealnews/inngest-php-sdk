    /**
     * Every JS fixture case has a PHP equivalent
     *
     * @return void
     */
    public function testAllFixtureCasesCovered(): void {
        $this->assertSame(
            array_keys($this->loadJsonFixture('functions/js-configs.json')),
            array_keys(static::parityProvider())
        );
    }

    /**
     * IDs, names, and getters
     *
     * @return void
     */
    public function testIdentity(): void {
        $handler = static fn () => 'ran';
        $failure = static fn () => 'failed';
        $options = new FunctionOptions(
            id: 'fn',
            description: 'desc',
            on_failure: $failure
        );
        $fn = new InngestFunction('app', $options, $handler);

        $this->assertSame('fn', $fn->id());
        $this->assertSame('app-fn', $fn->id('app'));
        $this->assertSame('fn', $fn->id(''));
        $this->assertSame('app-fn', $fn->absoluteId());
        $this->assertSame('app-fn-failure', $fn->failureId());
        $this->assertSame('fn', $fn->name());
        $this->assertSame('desc', $fn->description());
        $this->assertSame($options, $fn->getOptions());
        $this->assertSame('ran', ($fn->getHandler())());
        $this->assertSame('failed', ($fn->getFailureHandler())());
        $this->assertSame(['app-fn', 'app-fn-failure'], $fn->configIds());
    }

    /**
     * Without on_failure there's one config ID and no failure handler
     *
     * @return void
     */
    public function testWithoutFailureHandler(): void {
        $fn = new InngestFunction(
            'app',
            new FunctionOptions(id: 'fn', name: ''),
            static fn () => null
        );

        $this->assertNull($fn->getFailureHandler());
        $this->assertSame(['app-fn'], $fn->configIds());
        $this->assertSame('fn', $fn->name());
    }

    /**
     * Callable strings and arrays work as handlers
     *
     * @return void
     */
    public function testCallableHandler(): void {
        $fn = new InngestFunction(
            'app',
            new FunctionOptions(id: 'fn'),
            'strtoupper'
        );

        $this->assertSame('ABC', ($fn->getHandler())('abc'));
    }
