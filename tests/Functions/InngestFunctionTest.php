/**
 * Tests for InngestFunction
 *
 * Config output is compared against tests/fixtures/functions/
 * js-configs.json, generated by running the JS SDK's `getConfig()` on the
 * same definitions (see generate.mts there).
 *
 * @package DealNews\Inngest\Tests\Functions
 */
#[CoversClass(InngestFunction::class)]
#[UsesClass(BatchEvents::class)]
#[UsesClass(CancelConfig::class)]
#[UsesClass(Cancellation::class)]
#[UsesClass(Concurrency::class)]
