    /**
     * App ID used by the JS fixture generator
     *
     * @var string
     */
    public const APP_ID = 'testclient';

    /**
     * PHP configs match the JS SDK's getConfig() output for each case
     *
     * @param string          $case    Fixture case name
     * @param FunctionOptions $options PHP equivalent of the JS options
     *
     * @return void
     */
    #[DataProvider('parityProvider')]
    public function testConfigMatchesJs(
        string $case,
        FunctionOptions $options
    ): void {
        // Decode as objects so JS `{}` stays distinct from `[]`
        $fixture = json_decode(
            $this->loadFixture('functions/js-configs.json')
        )->$case;
        $fn = new InngestFunction(self::APP_ID, $options, fn () => null);

        $actual = json_encode(
            $fn->getConfigs($fixture->baseUrl),
            JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
        );

        $this->assertJsonDataSame(
            (string)json_encode($fixture->configs, JSON_UNESCAPED_SLASHES),
            (string)$actual,
            "Config for case \"$case\" differs from JS"
        );
    }

